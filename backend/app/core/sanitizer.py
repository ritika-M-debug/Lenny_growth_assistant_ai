import re
from typing import Tuple, Optional

# Dangerous tags that must never be executed or rendered in previews
DANGEROUS_TAGS_PATTERN = re.compile(
    r"<\s*(script|iframe|object|embed|applet|meta|link|base|form)\b[^>]*>.*?<\s*/\s*\1\s*>|"
    r"<\s*(script|iframe|object|embed|applet|meta|link|base|form)\b[^>]*\/?\s*>",
    re.IGNORECASE | re.DOTALL
)

# Dangerous inline event handlers like onload, onerror, onclick, onmouseover
EVENT_HANDLER_PATTERN = re.compile(
    r"\s+on[a-zA-Z]+\s*=\s*([\"'][^\"']*[\"']|[^\s>]+)",
    re.IGNORECASE
)

# Javascript pseudo-protocol URLs
JAVASCRIPT_URI_PATTERN = re.compile(
    r"(href|src|action)\s*=\s*[\"']\s*javascript:[^\"']*[\"']",
    re.IGNORECASE
)


def sanitize_html(raw_html: str) -> str:
    """
    Sanitizes untrusted HTML/CSS content generated by AI models.
    Removes executable scripts, event handlers, javascript URIs, and dangerous elements.
    Preserves valid styling, layouts, headings, sections, and structural HTML.
    """
    if not raw_html:
        return ""

    sanitized = raw_html

    # 1. Strip script, object, embed, iframe, form, and applet tags entirely
    sanitized = DANGEROUS_TAGS_PATTERN.sub("", sanitized)

    # 2. Strip inline event handlers (onerror=, onload=, onclick=, etc.)
    sanitized = EVENT_HANDLER_PATTERN.sub("", sanitized)

    # 3. Strip javascript: pseudo-protocol URIs
    sanitized = JAVASCRIPT_URI_PATTERN.sub(r'\1="#"', sanitized)

    return sanitized.strip()


def validate_artifact_payload(title: str, artifact_type: str, content: str) -> Tuple[bool, Optional[str]]:
    """
    Validates artifact attributes and safety boundaries.
    """
    if not title or len(title.strip()) == 0:
        return False, "Artifact title cannot be empty."
    if len(title) > 255:
        return False, "Artifact title exceeds maximum length of 255 characters."
    if artifact_type not in ["markdown", "html"]:
        return False, f"Invalid artifact type '{artifact_type}'. Allowed types are 'markdown' or 'html'."
    if not content or len(content.strip()) == 0:
        return False, "Artifact content cannot be empty."
    if len(content) > 500_000:
        return False, "Artifact content exceeds maximum allowed size of 500,000 characters."

    return True, None
